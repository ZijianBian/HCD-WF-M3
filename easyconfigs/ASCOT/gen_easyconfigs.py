def main():
    hcd.make_archive('ASCOT', REPO, COMMIT, 'ascot')
    sha = hcd.write_helper(
        os.path.join(HERE, HELPER), 'ascot_run_setup', 'ASCOT', 'ASCOT', 'EBROOTASCOT',
        'afsi_m3.exe, bbnbi_m3.exe, ascot_m3.exe, build stamp .build_combo', '<run_dir>', '',
        ['python run_ascot.py -c input   # iWrap actors (edit input/scenario.yaml first)',
         './run_muscle                   # MUSCLE3 actors bbnbi -> ascot (2 MPI processes each), afsi'])
    flavours = {k: {'deps': deps(tc, dd)} for k, (tc, dd, fc) in hcd.TC_DD_FC.items()}
    hcd.write_template(HERE, 'ASCOT', VERSION, TEMPLATE, flavours, {
        'COMMIT': COMMIT, 'DESCRIBE': DESCRIBE, 'HELPER': HELPER, 'HELPER_SHA': sha,
        'ACTORS': repr(ACTORS), 'UNSET': hcd.UNSET_TOOLCHAIN_ENV})


if __name__ == '__main__':
    main()
