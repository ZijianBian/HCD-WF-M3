#!/usr/bin/env python3
"""Writes the three CHEASE easyconfigs (DD4/2025b, DD3/2025b, DD3/2023b) next to this script, the
run-directory helper chease_run_setup.sh and the source archive
<work>/sources/c/CHEASE/chease-<VERSION>.tar.gz (git archive of COMMIT from the local chease
clone, prefix chease/).

Build as python/build.sh of the repository: ./build_imas.csh (tcsh; library src-f90/libchease_module_imas.a),
then the MUSCLE3 actor package (iwrap/chease_choices_M3.yaml, iWrap MUSCLE3 plugin) and the iWrap Python
actor package (iwrap/chease_choices.yaml), with the code parameters of python/config_sdcc*.sh (DD4: the
repository xml files, COCOS 17; DD3: copies with cocos_in / cocos_out 11). Module names differ from the
PDS module CHEASE/2026.08-intel-2025b-pds by the date label and the -DD-<dd> part.

Dependencies = the `modules` list of the matching combination of deps.yaml at the pinned commit, in the
same order (the local_modules of intel-2023b-dd3, yMMSL-dot, are interactive tools of the env file and
not part of it); tcsh for build_imas.csh: module tcsh/6.24.16-GCCcore-14.3.0 on intel-2025b, the
system tcsh on intel-2023b (no GCCcore-13.2.0 tcsh module). Rerun this script after editing the helper
template (its checksum is written into the easyconfigs).
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, '..', '_lib'))
import hcd_ec as hcd  # noqa: E402

# Version label = build date of the module; built from COMMIT (origin/feature/DD3_and_DD4,
# git describe DESCRIBE).
VERSION = hcd.version_of('CHEASE')
COMMIT = '834d4a516b07893d85e64554ae6654082b32096a'
DESCRIBE = 'crpptbx-9.6.0-deployed-crpptbx-release-v15.1.1-38-g834d4a5'
REPO = hcd.repo('chease', 'CHEASE')
HELPER = 'chease_run_setup.sh'


def deps(tc, dd):
    return [hcd.d_iwrap(), hcd.d_imaspy(), hcd.d_imasf(dd), hcd.d_muscle3(tc), hcd.d_xmllib(tc), hcd.d_interpos(tc),
            hcd.d_iwrap_m3plugin()]


TEMPLATE = '''# CHEASE (fixed-boundary equilibrium) as IMAS library, iWrap Python actor and iWrap MUSCLE3 actor:
# DD @DD@, toolchain intel/@TC@ (@FC@), combination @COMBO@ of deps.yaml.
# Generated by gen_easyconfigs.py; edit the generator, not this file.
easyblock = 'MakeCp'

name = 'CHEASE'
version = '@VERSION@'
local_dd = '@DD@'
versionsuffix = '-DD-%s' % local_dd

# Version @VERSION@ (date label) = commit @COMMIT@ of origin/feature/DD3_and_DD4,
# https://gitlab.epfl.ch/spc/chease.git (git describe @DESCRIBE@); source archive
# chease-@VERSION@.tar.gz = git archive --prefix=chease/ of that commit.
local_commit = '@COMMIT@'
local_combo = '@COMBO@'
local_fc = '@FC@'

homepage = 'https://gitlab.epfl.ch/spc/chease'
description = """CHEASE: fixed-boundary Grad-Shafranov equilibrium solver.
Version @VERSION@ is a date label: built from commit %s (git describe @DESCRIBE@) of
origin/feature/DD3_and_DD4, for DD %s, XML choices variant: library (lib, include/chease), iWrap Python
actor package chease (on PYTHONPATH), iWrap MUSCLE3 actor package chease_m3 (chease_m3/bin/chease.exe, also
chease/chease_m3.exe), code parameters codeparam/chease_input_{choices,reflist}.xml (COCOS 17 for DD 4, 11
for DD 3; CHEASE_CODEPARAM_CHOICES / CHEASE_CODEPARAM_REFLIST), and the run kit run_kit (python/run_chease.py,
python/run_muscle3, python/coupling.ymmsl, input); chease_run_setup <dir> makes a writable run directory from
it.""" % (local_commit, local_dd)

toolchain = {'name': 'intel', 'version': '@TC@'}

sources = [
    {
        'git_config': {
            'url': 'https://gitlab.epfl.ch/spc',
            'repo_name': 'chease',
            'commit': local_commit,
        },
        'filename': '%(namelower)s-%(version)s.tar.gz',
    },
    {
        'filename': '@HELPER@',
        'extract_cmd': 'cp %s .',
    },
]
checksums = [
    None,
    '@HELPER_SHA@',
]
start_dir = '%(builddir)s/chease'

@TCSH@

# combination @COMBO@ of deps.yaml (same order)
dependencies = [
@DEPS@
]

# Build environment of python/config_sdcc*.sh: no toolchain compiler flags, FC of the toolchain,
# COMBO and IMAS_VERSION of the combination, CHEASE settings and code parameters
local_codeparam = '%(builddir)s/codeparam'
local_env = ' && '.join([
    '@UNSET@',
    'export FC=%s COMBO=%s IMAS_VERSION=%s' % (local_fc, local_combo, local_dd),
    'export CHEASE_F90=$FC CHEASE_MACHINE=ITER XML_USE_CHOICE=YES',
    'export CHEASE_CODEPARAM_CHOICES=%s/chease_input_choices.xml' % local_codeparam,
    'export CHEASE_CODEPARAM_REFLIST=%s/chease_input_reflist.xml' % local_codeparam,
])
# ACTORS_COPY_DIR=none: ci-sdcc/copy_actors.sh of the build scripts copies no actor into ~/public/PYTHON_ACTORS
local_env += ' && export ACTORS_COPY_DIR=none'
# code parameters: the repository files (DD 4, COCOS 17), for DD 3 with cocos_in / cocos_out 17 -> 11
# (the sed of python/config_sdcc_dd3_*.sh)
if local_dd.startswith('3.'):
    local_codeparam_cmd = ('mkdir -p %s && for v in choices reflist; do sed -E '
                           '"s#(<cocos_(in|out)>[[:space:]]*)17([[:space:]]*</cocos_)#\\\\111\\\\3#" '
                           'input/chease_input_$v.xml > %s/chease_input_$v.xml; done' % (local_codeparam, local_codeparam))
else:
    local_codeparam_cmd = 'mkdir -p %s && cp -p input/chease_input_choices.xml input/chease_input_reflist.xml %s/' % (
        local_codeparam, local_codeparam)

# python/build.sh: ./build_imas.csh (src-f90: make clean; make libchease_module_imas)
prebuildopts = ' && '.join([
    local_env,
    local_codeparam_cmd,
    '',
])
build_cmd = './build_imas.csh'
maxparallel = 1

files_to_copy = [
    (['src-f90/libchease_module_imas.a'], 'lib'),
    (['src-f90/*.mod'], 'include/chease'),
]

local_kit = '%(installdir)s/run_kit'
postinstallcmds = [
    # python/build.sh: MUSCLE3 actor package (iWrap MUSCLE3 plugin), generated in the build directory and
    # installed as chease_m3, then the iWrap Python actor package chease in %(installdir)s
    local_env + ' && cd %(start_dir)s && iwrap -f iwrap/chease_choices_M3.yaml -i %(builddir)s/m3pkg'
    ' && cp -rp %(builddir)s/m3pkg/chease %(installdir)s/chease_m3',
    local_env + ' && cd %(start_dir)s && iwrap -f iwrap/chease_choices.yaml -i %(installdir)s',
    # MUSCLE3 executable in the HCD-WF layout <actor>/<actor>_m3.exe
    'ln -sfn ../chease_m3/bin/chease.exe %(installdir)s/chease/chease_m3.exe',
    'mkdir -p %(installdir)s/codeparam && cp -p ' + local_codeparam + '/chease_input_choices.xml '
    + local_codeparam + '/chease_input_reflist.xml %(installdir)s/codeparam/',
    # run kit: python/ (without the env files) and input/; ./chease is a link to the MUSCLE3 actor package
    # (coupling.ymmsl: ../../../../../chease/bin/chease.exe seen from python/run_*/instances/*/workdir)
    'mkdir -p ' + local_kit + ' && cd %(start_dir)s'
    " && tar --exclude='config_*.sh' --exclude=__pycache__ -cf - python input | tar -xf - -C " + local_kit,
    'cd ' + local_kit + ' && chmod a+x python/run_muscle3 python/build.sh'
    ' && ln -sfn %(installdir)s/chease_m3 chease',
    # build stamp of the combination (read by python/run_muscle3 and python/run_chease.py)
    local_env + ' && cd ' + local_kit + ' && bash python/ci-sdcc/build_stamp.sh write python',
    'mkdir -p %(installdir)s/bin && install -m 0755 %(builddir)s/@HELPER@ %(installdir)s/bin/chease_run_setup',
    'find %(installdir)s -name __pycache__ -type d -prune -exec rm -rf {} +',
]

modextrapaths = {'PYTHONPATH': ''}
modextravars = {
    'IMAS_VERSION': local_dd,
    'COMBO': local_combo,
    'XML_USE_CHOICE': 'YES',
    'CHEASE_CODEPARAM_CHOICES': '%(installdir)s/codeparam/chease_input_choices.xml',
    'CHEASE_CODEPARAM_REFLIST': '%(installdir)s/codeparam/chease_input_reflist.xml',
    'CHEASE_RUN_KIT': local_kit,
}
# stack limit of config_sdcc*.sh (Fortran automatic arrays)
modluafooter = 'execute{cmd="ulimit -Ss unlimited 2>/dev/null || true", modeA={"load"}}'

sanity_check_paths = {
    'files': ['lib/libchease_module_imas.a', 'include/chease/chease_module.mod', 'bin/chease_run_setup',
              'chease/actor.py', 'chease/chease_m3.exe', 'chease_m3/bin/chease.exe',
              'codeparam/chease_input_choices.xml', 'codeparam/chease_input_reflist.xml',
              'run_kit/python/run_chease.py', 'run_kit/python/run_muscle3', 'run_kit/python/coupling.ymmsl',
              'run_kit/python/.build_combo', 'run_kit/chease/bin/chease.exe'],
    'dirs': ['chease_m3/input', 'run_kit/input'],
}

sanity_check_commands = [
    "python -c 'from chease.actor import chease'",
    "python -c 'import ymmsl, libmuscle'",
    "! ldd %(installdir)s/chease_m3/bin/chease.exe | grep 'not found'",
    "ldd %(installdir)s/chease_m3/bin/chease.exe | grep -q libmuscle",
    "grep -Eq '<cocos_in>[[:space:]]*%s[[:space:]]*</cocos_in>' %%(installdir)s/codeparam/chease_input_choices.xml" % (
        '17' if local_dd.startswith('4') else '11'),
    'test "$IMAS_VERSION" = "$(pkg-config --modversion al-fortran | cut -d- -f1)"',
    'bash %(installdir)s/run_kit/python/ci-sdcc/build_stamp.sh check %(installdir)s/run_kit/python chease',
    'chease_run_setup --help',
]

moduleclass = 'phys'
'''

TCSH_2025B = '''# tcsh for build_imas.csh
builddependencies = [
    ('tcsh', '6.24.16', '', ('GCCcore', '14.3.0')),
]'''
TCSH_2023B = '''# tcsh for build_imas.csh: no tcsh module for GCCcore-13.2.0, the system tcsh
osdependencies = ['tcsh']'''


def main():
    hcd.make_archive('CHEASE', REPO, COMMIT, 'chease')
    sha = hcd.write_helper(
        os.path.join(HERE, HELPER), 'chease_run_setup', 'CHEASE', 'CHEASE', 'EBROOTCHEASE',
        'chease/ = MUSCLE3 actor package, build stamp python/.build_combo', '<run_dir>/python', '/python',
        ['python run_chease.py --scenario <scenario.yaml>          # iWrap actor (default ../input/scenario.yaml)',
         'CHEASE_SCENARIO=<scenario.yaml> ./run_muscle3          # MUSCLE3 actor'])
    flavours = {}
    for k, (tc, dd, fc) in hcd.TC_DD_FC.items():
        flavours[k] = {'deps': deps(tc, dd), 'TCSH': TCSH_2025B if tc == '2025b' else TCSH_2023B}
    hcd.write_template(HERE, 'CHEASE', VERSION, TEMPLATE, flavours, {
        'COMMIT': COMMIT, 'DESCRIBE': DESCRIBE, 'HELPER': HELPER, 'HELPER_SHA': sha,
        'UNSET': hcd.UNSET_TOOLCHAIN_ENV})


if __name__ == '__main__':
    main()
