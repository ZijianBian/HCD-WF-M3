#!/usr/bin/env python3
"""Writes the three HCD2CORE_PROFILES easyconfigs (DD4/2025b, DD3/2025b, DD3/2023b) next to this
script, the run-directory helper hcd2core_profiles_run_setup.sh and the source archive
<work>/sources/h/HCD2CORE_PROFILES/hcd2core_profiles-<VERSION>.tar.gz (git archive of COMMIT
from the local hcd2core-profiles clone, prefix hcd2core-profiles/).

Dependencies = the `modules` list of the matching combination of deps.yaml at the pinned commit,
in the same order (deps.yaml lists no components). Rerun this script after editing the helper
template (its checksum is written into the easyconfigs).
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, '..', '_lib'))
import hcd_ec as hcd  # noqa: E402

# Version label = build date of the module; built from COMMIT (origin/feature/DD3_and_DD4,
# git describe DESCRIBE). The staged .gitignore and env-file edits of the clone are not part of it.
VERSION = hcd.version_of('HCD2CORE_PROFILES')
COMMIT = '024c36eb1dd9049b2bd5708d236b9f0631160e5f'
DESCRIBE = '1.1.0-8-g024c36e'
REPO = hcd.repo('hcd2core-profiles', 'HCD2CORE_PROFILES')
HELPER = 'hcd2core_profiles_run_setup.sh'


def deps(tc, dd):
    return [hcd.d_iwrap(), hcd.d_imaspy(), hcd.d_imasf(dd), hcd.d_idstools(), hcd.d_xmllib(tc), hcd.d_interpos(tc),
            hcd.d_muscle3(tc)]


TEMPLATE = '''# HCD2CORE_PROFILES (fast-particle contributions of distributions to core_profiles) as Fortran library,
# iWrap actor and MUSCLE3 actor: DD @DD@, toolchain intel/@TC@ (@FC@), combination @COMBO@ of deps.yaml.
# Generated by gen_easyconfigs.py; edit the generator, not this file.
easyblock = 'MakeCp'

name = 'HCD2CORE_PROFILES'
version = '@VERSION@'
local_dd = '@DD@'
versionsuffix = '-DD-%s' % local_dd

# Version @VERSION@ (date label) = commit @COMMIT@ of origin/feature/DD3_and_DD4,
# ssh://git@git.iter.org/heat/hcd2core-profiles.git (git describe @DESCRIBE@); source archive
# hcd2core_profiles-@VERSION@.tar.gz = git archive --prefix=hcd2core-profiles/ of that commit.
local_commit = '@COMMIT@'
local_combo = '@COMBO@'
local_fc = '@FC@'

homepage = 'https://git.iter.org/projects/HEAT/repos/hcd2core-profiles'
description = """hcd2core_profiles: fast-particle densities and pressures of the distributions IDS into core_profiles.
Version @VERSION@ is a date label: built from commit %s (git describe @DESCRIBE@) of
origin/feature/DD3_and_DD4, for DD %s (DEBUG=yes build, as the CI and the committed iWrap yamls): Fortran
library (lib, include/hcd2core_profiles), test program bin/prog_hcd2core_profiles.exe, iWrap actor package
hcd2core_profiles (on PYTHONPATH) with its MUSCLE3 actor hcd2core_profiles/hcd2core_profiles_m3.exe (also in
bin), and the run kit run_kit (run_hcd2core_profilescode, run_hcd2core_profiles.py, run_muscle,
coupling.ymmsl, input); hcd2core_profiles_run_setup <dir> makes a writable run directory from it.""" % (
    local_commit, local_dd)

toolchain = {'name': 'intel', 'version': '@TC@'}

sources = [
    {
        'git_config': {
            'url': 'ssh://git@git.iter.org/heat',
            'repo_name': 'hcd2core-profiles',
            'commit': local_commit,
        },
        'filename': '%(namelower)s-%(version)s.tar.gz',
    },
    {
        'filename': '@HELPER@',
        'extract_cmd': 'cp %s .',
    },
]
checksums = [
    None,
    '@HELPER_SHA@',
]
start_dir = '%(builddir)s/hcd2core-profiles'

dependencies = [
@DEPS@
]

# Build environment of ci-sdcc/st00-header.sh: no toolchain compiler flags, FC of the toolchain,
# COMBO and IMAS_VERSION of the combination
local_env = ' && '.join([
    '@UNSET@',
    'export FC=%s COMBO=%s IMAS_VERSION=%s' % (local_fc, local_combo, local_dd),
])
# ACTORS_COPY_DIR=none: ci-sdcc/copy_actors.sh of the build scripts copies no actor into ~/public/PYTHON_ACTORS
local_env += ' && export ACTORS_COPY_DIR=none'

# st01-build-code.sh: library (DEBUG=yes), then the standalone test program (make test runs it)
prebuildopts = ' && '.join([
    local_env,
    'make -C src/ clean veryclean info validate library DEBUG=yes FC=$FC',
    '',
])
buildopts = '-C src/ DEBUG=yes FC=%s' % local_fc
build_cmd_targets = 'test'
maxparallel = 1

files_to_copy = [
    (['src/build/lib/debug/libhcd2core_profiles.a'], 'lib'),
    (['src/build/obj/debug/*.mod'], 'include/hcd2core_profiles'),
    (['src/build/bin/debug/prog_hcd2core_profiles.exe'], 'bin'),
]

local_kit = '%(installdir)s/run_kit'
postinstallcmds = [
    # st02-build-actor.sh: iWrap actor (yaml per FC and DD) and MUSCLE3 actor in
    # ACTOR_FOLDER=%(installdir)s (hcd2core_profiles/hcd2core_profiles_m3.exe, where coupling.ymmsl expects it)
    local_env + ' && cd %(start_dir)s && make -C src/ iwrapactor FC=$FC DEBUG=yes ACTOR_FOLDER=%(installdir)s',
    local_env + ' && cd %(start_dir)s && make -C src/ m3 FC=$FC DEBUG=yes ACTOR_FOLDER=%(installdir)s',
    'cp -p %(start_dir)s/src/hcd2core_profiles_m3.exe %(installdir)s/bin/',
    # run kit: run scripts and inputs of the repository root; the actor folder is a link to the module
    'mkdir -p ' + local_kit + ' && cd %(start_dir)s'
    ' && cp -p run_hcd2core_profilescode run_hcd2core_profiles.py run_muscle coupling.ymmsl build.sh ' + local_kit + '/'
    ' && cp -rp input ci-sdcc ' + local_kit + '/',
    'cd ' + local_kit + ' && chmod a+x run_hcd2core_profilescode run_hcd2core_profiles.py run_muscle build.sh'
    ' && ln -sfn %(installdir)s/hcd2core_profiles hcd2core_profiles',
    # build stamp of the combination (read by run_muscle through ci-sdcc/build_stamp.sh)
    local_env + ' && cd ' + local_kit + ' && bash ci-sdcc/build_stamp.sh write .',
    'install -m 0755 %(builddir)s/@HELPER@ %(installdir)s/bin/hcd2core_profiles_run_setup',
    'find %(installdir)s -name __pycache__ -type d -prune -exec rm -rf {} +',
]

modextrapaths = {'PYTHONPATH': ''}
modextravars = {
    'IMAS_VERSION': local_dd,
    'COMBO': local_combo,
    'HCD2CORE_PROFILES_RUN_KIT': local_kit,
}
# stack limit of config_sdcc*.sh (Fortran automatic arrays)
modluafooter = 'execute{cmd="ulimit -Ss unlimited 2>/dev/null || true", modeA={"load"}}'

sanity_check_paths = {
    'files': ['lib/libhcd2core_profiles.a', 'include/hcd2core_profiles/hcd2core_profiles_module.mod',
              'bin/prog_hcd2core_profiles.exe', 'bin/hcd2core_profiles_m3.exe', 'bin/hcd2core_profiles_run_setup',
              'hcd2core_profiles/actor.py', 'hcd2core_profiles/hcd2core_profiles_m3.exe',
              'run_kit/run_hcd2core_profilescode', 'run_kit/run_muscle', 'run_kit/coupling.ymmsl',
              'run_kit/.build_combo', 'run_kit/ci-sdcc/build_stamp.sh'],
    'dirs': ['run_kit/input', 'hcd2core_profiles/input'],
}

sanity_check_commands = [
    "python -c 'from hcd2core_profiles.actor import hcd2core_profiles'",
    "python -c 'import ymmsl, libmuscle'",
    "! ldd %(installdir)s/hcd2core_profiles/hcd2core_profiles_m3.exe | grep 'not found'",
    "ldd %(installdir)s/hcd2core_profiles/hcd2core_profiles_m3.exe | grep -q libmuscle",
    'test "$IMAS_VERSION" = "$(pkg-config --modversion al-fortran | cut -d- -f1)"',
    'bash %(installdir)s/run_kit/ci-sdcc/build_stamp.sh check %(installdir)s/run_kit hcd2core-profiles',
    'hcd2core_profiles_run_setup --help',
]

moduleclass = 'phys'
'''


def main():
    hcd.make_archive('HCD2CORE_PROFILES', REPO, COMMIT, 'hcd2core-profiles')
    sha = hcd.write_helper(
        os.path.join(HERE, HELPER), 'hcd2core_profiles_run_setup', 'HCD2CORE_PROFILES', 'HCD2CORE_PROFILES',
        'EBROOTHCD2CORE_PROFILES', 'hcd2core_profiles/ with the MUSCLE3 actor, build stamp .build_combo',
        '<run_dir>', '',
        ['./run_hcd2core_profilescode --src <uri> --dest <uri> --time <s>   # iWrap actor (CI case)',
         './run_muscle   # MUSCLE3 actor; edit --src/--dest/--time in coupling.ymmsl first'])
    flavours = {k: {'deps': deps(tc, dd)} for k, (tc, dd, fc) in hcd.TC_DD_FC.items()}
    hcd.write_template(HERE, 'HCD2CORE_PROFILES', VERSION, TEMPLATE, flavours, {
        'COMMIT': COMMIT, 'DESCRIBE': DESCRIBE, 'HELPER': HELPER, 'HELPER_SHA': sha,
        'UNSET': hcd.UNSET_TOOLCHAIN_ENV})


if __name__ == '__main__':
    main()
