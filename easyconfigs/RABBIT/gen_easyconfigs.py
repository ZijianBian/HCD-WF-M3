#!/usr/bin/env python3
"""Writes the three RABBIT easyconfigs (DD4/2025b, DD3/2025b, DD3/2023b) next to this script, the
run-directory helper rabbit_run_setup.sh and the source archive
<work>/sources/r/RABBIT/rabbit-<VERSION>.tar.gz (git archive of COMMIT from the local rabbit
clone, prefix rabbit/).

Dependencies = the `modules` list of the matching combination of deps.yaml at the pinned commit, in
the same order, CMake (build tool of the list) as build dependency, then the waveform_cooker component
(Waveform-Cooker 1.9.0, the module deps.yaml names). Rerun this script after editing the helper
template (its checksum is written into the easyconfigs).
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, '..', '_lib'))
import hcd_ec as hcd  # noqa: E402

# Version label = build date of the module; built from COMMIT (origin/feature/DD3_and_DD4,
# git describe DESCRIBE).
VERSION = hcd.version_of('RABBIT')
COMMIT = '5d5097c0964b6b1ca1b94cbca6a0de0624c09c6e'
DESCRIBE = '5.0.2-159-g5d5097c'
REPO = hcd.repo('rabbit', 'RABBIT')
HELPER = 'rabbit_run_setup.sh'


def deps(tc, dd):
    return [hcd.d_iwrap(), hcd.d_imaspy(), hcd.d_imasf(dd), hcd.d_idstools(), hcd.d_muscle3(tc), hcd.d_xmllib(tc),
            hcd.d_interpos(tc), hcd.d_netcdff(tc), hcd.d_wfc190(tc)]


TEMPLATE = '''# RABBIT (NBI fast-ion code) as IMAS library, iWrap actor and MUSCLE3 actor: DD @DD@, toolchain
# intel/@TC@ (@FC@), combination @COMBO@ of deps.yaml.
# Generated by gen_easyconfigs.py; edit the generator, not this file.
easyblock = 'MakeCp'

name = 'RABBIT'
version = '@VERSION@'
local_dd = '@DD@'
versionsuffix = '-DD-%s' % local_dd

# Version @VERSION@ (date label) = commit @COMMIT@ of origin/feature/DD3_and_DD4,
# ssh://git@git.iter.org/heat/rabbit.git (git describe @DESCRIBE@); source archive
# rabbit-@VERSION@.tar.gz = git archive --prefix=rabbit/ of that commit.
local_commit = '@COMMIT@'
local_combo = '@COMBO@'
local_fc = '@FC@'

homepage = 'https://git.iter.org/projects/HEAT/repos/rabbit'
description = """RABBIT: fast NBI deposition, slowing-down and current-drive code.
Version @VERSION@ is a date label: built from commit %s (git describe @DESCRIBE@) of
origin/feature/DD3_and_DD4, for DD %s: IMAS library (lib, include/rabbit), bin/rabbit_imas.exe, MUSCLE3
actor bin/rabbit_m3.exe (also rabbit/rabbit_m3.exe, where HCD-WF expects it), iWrap actor package rabbit
(on PYTHONPATH), and the run kit run_kit (a copy of imas/: run_rabbit.py, run_muscle, coupling.ymmsl,
input, ci-sdcc); rabbit_run_setup <dir> makes a writable run directory from it. Release build without
-xHost (the module serves all node types).""" % (local_commit, local_dd)

toolchain = {'name': 'intel', 'version': '@TC@'}

sources = [
    {
        'git_config': {
            'url': 'ssh://git@git.iter.org/heat',
            'repo_name': 'rabbit',
            'commit': local_commit,
        },
        'filename': '%(namelower)s-%(version)s.tar.gz',
    },
    {
        'filename': '@HELPER@',
        'extract_cmd': 'cp %s .',
    },
]
checksums = [
    None,
    '@HELPER_SHA@',
]
start_dir = '%(builddir)s/rabbit/imas'

builddependencies = [
@BUILDDEPS@
]

# combination @COMBO@ of deps.yaml (same order, CMake as build dependency), then Waveform-Cooker
dependencies = [
@DEPS@
]

# Build environment of ci-sdcc/st00-header.sh: no toolchain compiler flags, FC of the toolchain,
# COMBO and IMAS_VERSION of the combination
local_env = ' && '.join([
    '@UNSET@',
    'export FC=%s COMBO=%s IMAS_VERSION=%s' % (local_fc, local_combo, local_dd),
])
# ACTORS_COPY_DIR=none: ci-sdcc/copy_actors.sh of the build scripts copies no actor into ~/public/PYTHON_ACTORS
local_env += ' && export ACTORS_COPY_DIR=none'

# st01-build-code.sh (imas/build.sh lib, release build) with -xHost removed from the Intel release
# flags of the root CMakeLists.txt: the module is shared by all node types (rigel has no AVX-512)
prebuildopts = ' && '.join([
    local_env,
    "sed -i -e 's/ -xHost / /g' ../CMakeLists.txt",
    "! grep -n -- ' -xHost ' ../CMakeLists.txt",
    'BUILD_JOBS=2 ./build.sh lib',
    '',
])
# the targets of build.sh lib again (up to date: nothing to do), as check of the build tree
buildopts = '-C build'
build_cmd_targets = 'rabbitA_imas rabbit_imas.exe rabbit_m3.exe'
maxparallel = 1

files_to_copy = [
    (['build/imas/librabbit_imas.a'], 'lib'),
    (['build/modules/*.mod'], 'include/rabbit'),
    (['build/imas/rabbit_imas.exe', 'build/imas/rabbit_m3.exe'], 'bin'),
]

local_kit = '%(installdir)s/run_kit'
postinstallcmds = [
    # st02-build-actor.sh (imas/build.sh actor): iWrap actor in ACTOR_FOLDER=%(installdir)s (yaml per FC
    # and DD), with a copy of rabbit_m3.exe (rabbit/rabbit_m3.exe, used by HCD-WF)
    local_env + ' && cd %(start_dir)s && ACTOR_FOLDER=%(installdir)s ./build.sh actor',
    # run kit: imas/ without the build tree; build/imas/rabbit_m3.exe (coupling.ymmsl) and the actor
    # package are links to the module
    'mkdir -p ' + local_kit + '/build/imas && cd %(start_dir)s'
    ' && cp -p run_rabbit.py time_compute.py run_muscle coupling.ymmsl coupling_hcd2cs.ymmsl build.sh ' + local_kit + '/'
    ' && cp -rp input ci-sdcc ' + local_kit + '/',
    'cd ' + local_kit + ' && chmod a+x run_rabbit.py run_muscle build.sh'
    ' && ln -sfn %(installdir)s/bin/rabbit_m3.exe build/imas/rabbit_m3.exe'
    ' && ln -sfn %(installdir)s/rabbit rabbit',
    # build stamp of the combination (read by run_muscle and run_rabbit.py through ci-sdcc/build_stamp.sh)
    local_env + ' && cd ' + local_kit + ' && bash ci-sdcc/build_stamp.sh write .',
    'install -m 0755 %(builddir)s/@HELPER@ %(installdir)s/bin/rabbit_run_setup',
    'find %(installdir)s -name __pycache__ -type d -prune -exec rm -rf {} +',
]

modextrapaths = {'PYTHONPATH': ''}
modextravars = {
    'IMAS_VERSION': local_dd,
    'COMBO': local_combo,
    'IMAS_AL_DISABLE_OBSOLESCENT_WARNING': '1',
    'IMAS_AL_DISABLE_VALIDATE': '1',
    # stack of the OpenMP threads (one per beam): the Intel default (4 MB) is too small for RABBIT
    'OMP_STACKSIZE': '64M',
    'RABBIT_RUN_KIT': local_kit,
}
# stack limit of config_sdcc*.sh (Fortran automatic arrays)
modluafooter = 'execute{cmd="ulimit -Ss unlimited 2>/dev/null || true", modeA={"load"}}'

sanity_check_paths = {
    'files': ['lib/librabbit_imas.a', 'include/rabbit/mod_rabbit_ids.mod', 'bin/rabbit_imas.exe',
              'bin/rabbit_m3.exe', 'bin/rabbit_run_setup', 'rabbit/actor.py', 'rabbit/rabbit_m3.exe',
              'run_kit/run_rabbit.py', 'run_kit/run_muscle', 'run_kit/coupling.ymmsl', 'run_kit/.build_combo',
              'run_kit/build/imas/rabbit_m3.exe', 'run_kit/ci-sdcc/st03-run-actor.sh'],
    'dirs': ['run_kit/input', 'rabbit/input'],
}

sanity_check_commands = [
    "python -c 'from rabbit.actor import rabbit'",
    "python -c 'import waveform_cooker, idstools, scipy, ymmsl, libmuscle'",
    "! ldd %(installdir)s/bin/rabbit_m3.exe | grep 'not found'",
    "! ldd %(installdir)s/bin/rabbit_imas.exe | grep 'not found'",
    "ldd %(installdir)s/bin/rabbit_m3.exe | grep -q libmuscle",
    'test "$IMAS_VERSION" = "$(pkg-config --modversion al-fortran | cut -d- -f1)"',
    'bash %(installdir)s/run_kit/ci-sdcc/build_stamp.sh check %(installdir)s/run_kit rabbit',
    'rabbit_run_setup --help',
]

moduleclass = 'phys'
'''


def main():
    hcd.make_archive('RABBIT', REPO, COMMIT, 'rabbit')
    sha = hcd.write_helper(
        os.path.join(HERE, HELPER), 'rabbit_run_setup', 'RABBIT', 'RABBIT', 'EBROOTRABBIT',
        'build/imas/rabbit_m3.exe, rabbit/ actor package, build stamp .build_combo', '<run_dir>', '',
        ['python run_rabbit.py -c input   # iWrap actor (edit input/scenario.yaml first)',
         './run_muscle                    # MUSCLE3 actor (RABBIT_CONFIG_FOLDER, default input/)'])
    flavours = {}
    for k, (tc, dd, fc) in hcd.TC_DD_FC.items():
        flavours[k] = {'builddeps': [hcd.d_cmake(tc)], 'deps': deps(tc, dd)}
    hcd.write_template(HERE, 'RABBIT', VERSION, TEMPLATE, flavours, {
        'COMMIT': COMMIT, 'DESCRIBE': DESCRIBE, 'HELPER': HELPER, 'HELPER_SHA': sha,
        'UNSET': hcd.UNSET_TOOLCHAIN_ENV})


if __name__ == '__main__':
    main()
