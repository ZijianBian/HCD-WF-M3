#!/usr/bin/env python3
"""Writes the three RISK easyconfigs (DD4/2025b, DD3/2025b, DD3/2023b) next to this script, the
run-directory helper risk_run_setup.sh and the source archive
<work>/sources/r/RISK/risk-<VERSION>.tar.gz (git archive of COMMIT from the local risk clone,
prefix risk/).

Dependencies = the `modules` list of the matching combination of deps.yaml at the pinned commit, in
the same order, then the waveform_cooker component (Waveform-Cooker 1.9.0, the module deps.yaml names).
MPI (Intel MPI) comes from the toolchain. The grid library is the in-tree ggd-light grid_library (no GGD
module). Rerun this script after editing the helper template (its checksum is written into the
easyconfigs).
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, '..', '_lib'))
import hcd_ec as hcd  # noqa: E402

# Version label = build date of the module; built from COMMIT (origin/feature/DD3_and_DD4,
# git describe DESCRIBE). The modified configuration files of the clone (input/input_chease.xml,
# input/scenario.yaml, env files) are not part of it.
VERSION = hcd.version_of('RISK')
COMMIT = '34e56cac760a990eba9f23a8e9612ac9f300ad4b'
DESCRIBE = '2.2.0-12-g34e56ca'
REPO = hcd.repo('risk', 'RISK')
HELPER = 'risk_run_setup.sh'


def deps(tc, dd):
    return [hcd.d_iwrap(), hcd.d_imaspy(), hcd.d_imasf(dd), hcd.d_idstools(), hcd.d_muscle3(tc), hcd.d_xmllib(tc),
            hcd.d_interpos(tc), hcd.d_wfc190(tc)]


TEMPLATE = '''# RISK (fast-ion Fokker-Planck code, MPI) as IMAS library, iWrap actor and MUSCLE3 actor: DD @DD@,
# toolchain intel/@TC@ (@FC@, Intel MPI), combination @COMBO@ of deps.yaml.
# Generated by gen_easyconfigs.py; edit the generator, not this file.
easyblock = 'MakeCp'

name = 'RISK'
version = '@VERSION@'
local_dd = '@DD@'
versionsuffix = '-DD-%s' % local_dd

# Version @VERSION@ (date label) = commit @COMMIT@ of origin/feature/DD3_and_DD4,
# ssh://git@git.iter.org/heat/risk.git (git describe @DESCRIBE@); source archive
# risk-@VERSION@.tar.gz = git archive --prefix=risk/ of that commit.
local_commit = '@COMMIT@'
local_combo = '@COMBO@'
local_fc = '@FC@'

homepage = 'https://git.iter.org/projects/HEAT/repos/risk'
description = """RISK: fast-ion Fokker-Planck code for NBI and fusion-born ions (MPI).
Version @VERSION@ is a date label: built from commit %s (git describe @DESCRIBE@) of
origin/feature/DD3_and_DD4, for DD %s, with FRUIT tests: library (lib, include/risk), MPI MUSCLE3 actor
bin/risk_m3.exe (also risk/risk_m3.exe), iWrap actor package risk (on PYTHONPATH), and the run kit
run_kit (run_risk, run_muscle, coupling.ymmsl, input, ci-sdcc); risk_run_setup <dir> makes a writable
run directory from it.""" % (local_commit, local_dd)

toolchain = {'name': 'intel', 'version': '@TC@'}

sources = [
    {
        'git_config': {
            'url': 'ssh://git@git.iter.org/heat',
            'repo_name': 'risk',
            'commit': local_commit,
        },
        'filename': '%(namelower)s-%(version)s.tar.gz',
    },
    {
        'filename': '@HELPER@',
        'extract_cmd': 'cp %s .',
    },
]
checksums = [
    None,
    '@HELPER_SHA@',
]
start_dir = '%(builddir)s/risk'

# combination @COMBO@ of deps.yaml (same order), then Waveform-Cooker
dependencies = [
@DEPS@
]

# Build environment of ci-sdcc/st00-header.sh: no toolchain compiler flags, FC of the toolchain,
# COMBO and IMAS_VERSION of the combination
local_env = ' && '.join([
    '@UNSET@',
    'export FC=%s COMBO=%s IMAS_VERSION=%s' % (local_fc, local_combo, local_dd),
])
# ACTORS_COPY_DIR=none: ci-sdcc/copy_actors.sh of the build scripts copies no actor into ~/public/PYTHON_ACTORS
local_env += ' && export ACTORS_COPY_DIR=none'
local_make_opts = 'FCOMPILER=%s USE_FRUIT=yes' % local_fc

# st01-build-code.sh: library (with the in-tree grid_library), then the MPI MUSCLE3 actor risk_m3.exe
prebuildopts = ' && '.join([
    local_env,
    'make clean library ' + local_make_opts,
    '',
])
buildopts = local_make_opts
build_cmd_targets = 'm3'
# the Makefile archives obj_<FC>/*.o: serial build
maxparallel = 1

files_to_copy = [
    (['obj_%s/librisk.a' % local_fc], 'lib'),
    (['obj_%s/*.mod' % local_fc], 'include/risk'),
    (['risk_m3.exe'], 'bin'),
]

local_kit = '%(installdir)s/run_kit'
postinstallcmds = [
    # st02-build-actor.sh: iWrap actor (yaml per FC and DD) in ACTOR_FOLDER=%(installdir)s, with a copy of
    # the MUSCLE3 actor (risk/risk_m3.exe)
    local_env + ' && cd %(start_dir)s && make actor ' + local_make_opts + ' ACTOR_FOLDER=%(installdir)s',
    'cp -p %(start_dir)s/risk_m3.exe %(installdir)s/risk/',
    # run kit: run scripts and inputs of the repository root; risk_m3.exe (coupling.ymmsl) and the actor
    # package ./risk (ci-sdcc/st03-run-actor.sh) are links to the module
    'mkdir -p ' + local_kit + ' && cd %(start_dir)s'
    ' && cp -p run_risk run_riskcode run_muscle coupling.ymmsl dd_compat.py time_compute.py build.sh ' + local_kit + '/'
    ' && cp -rp input ci-sdcc ' + local_kit + '/',
    'cd ' + local_kit + ' && chmod a+x run_risk run_riskcode run_muscle build.sh'
    ' && ln -sfn %(installdir)s/bin/risk_m3.exe risk_m3.exe'
    ' && ln -sfn %(installdir)s/risk risk',
    # build stamp of the combination (read by run_muscle through ci-sdcc/build_stamp.sh)
    local_env + ' && cd ' + local_kit + ' && bash ci-sdcc/build_stamp.sh write .',
    'install -m 0755 %(builddir)s/@HELPER@ %(installdir)s/bin/risk_run_setup',
    'find %(installdir)s -name __pycache__ -type d -prune -exec rm -rf {} +',
]

modextrapaths = {'PYTHONPATH': ''}
modextravars = {
    'IMAS_VERSION': local_dd,
    'COMBO': local_combo,
    'RISK_RUN_KIT': local_kit,
}
# stack limit of config_sdcc*.sh (Fortran automatic arrays)
modluafooter = 'execute{cmd="ulimit -Ss unlimited 2>/dev/null || true", modeA={"load"}}'

sanity_check_paths = {
    'files': ['lib/librisk.a', 'bin/risk_m3.exe', 'bin/risk_run_setup', 'risk/actor.py', 'risk/risk_m3.exe',
              'run_kit/run_risk', 'run_kit/run_muscle', 'run_kit/coupling.ymmsl', 'run_kit/.build_combo',
              'run_kit/risk_m3.exe', 'run_kit/ci-sdcc/st03-run-actor.sh', 'run_kit/ci-sdcc/st05-run-actor.sh'],
    'dirs': ['include/risk', 'run_kit/input', 'risk/input'],
}

sanity_check_commands = [
    "python -c 'from risk.actor import risk'",
    "python -c 'import waveform_cooker, idstools, scipy, ymmsl, libmuscle'",
    "! ldd %(installdir)s/bin/risk_m3.exe | grep 'not found'",
    "ldd %(installdir)s/bin/risk_m3.exe | grep -q libmuscle_mpi",
    'test "$IMAS_VERSION" = "$(pkg-config --modversion al-fortran | cut -d- -f1)"',
    'bash %(installdir)s/run_kit/ci-sdcc/build_stamp.sh check %(installdir)s/run_kit risk',
    'risk_run_setup --help',
]

moduleclass = 'phys'
'''


def main():
    hcd.make_archive('RISK', REPO, COMMIT, 'risk')
    sha = hcd.write_helper(
        os.path.join(HERE, HELPER), 'risk_run_setup', 'RISK', 'RISK', 'EBROOTRISK',
        'risk_m3.exe, risk/ actor package, build stamp .build_combo', '<run_dir>', '',
        ['./run_risk -c input   # iWrap actor (MPI processes: nproc of input/scenario.yaml)',
         './run_muscle          # MUSCLE3 actor (risk_m3.exe on resources.risk.mpi_processes)'])
    flavours = {k: {'deps': deps(tc, dd)} for k, (tc, dd, fc) in hcd.TC_DD_FC.items()}
    hcd.write_template(HERE, 'RISK', VERSION, TEMPLATE, flavours, {
        'COMMIT': COMMIT, 'DESCRIBE': DESCRIBE, 'HELPER': HELPER, 'HELPER_SHA': sha,
        'UNSET': hcd.UNSET_TOOLCHAIN_ENV})


if __name__ == '__main__':
    main()
