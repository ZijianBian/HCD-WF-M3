def main():
    hcd.make_archive('TORBEAM', REPO, COMMIT, 'torbeam')
    if hcd.SOURCES_ONLY:
        return
    helper_sha = hcd.sha256(os.path.join(HERE, 'torbeam_run_setup.sh'))
    for key, fl in FLAVOURS.items():
        text = TEMPLATE
        subst = {
            'VERSION': VERSION, 'COMMIT': COMMIT, 'DD': fl['dd'], 'TC': fl['toolchain'], 'FC': fl['fc'],
            'COMBO': fl['combo'], 'DESCRIBE': DESCRIBE, 'YAML': fl['yaml'], 'TREE': fl['tree'], 'XHOST': fl['xhost'], 'HELPER_SHA': helper_sha,
            'BUILDDEPS': '\n'.join(hcd.fmt_dep(d) for d in fl['builddeps']),
            'DEPS': '\n'.join(hcd.fmt_dep(d) for d in fl['deps']),
        }
        for k, v in subst.items():
            text = text.replace('@%s@' % k, v)
        assert '@' not in text.replace('git@git', ''), key
        hcd.write_file(os.path.join(HERE, 'TORBEAM-%s-intel-%s-DD-%s.eb' % (VERSION, fl['toolchain'], fl['dd'])),
                       text)


if __name__ == '__main__':
    main()
