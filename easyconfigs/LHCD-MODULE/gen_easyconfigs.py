#!/usr/bin/env python3
"""Writes the three LHCD-MODULE easyconfigs (DD4/2025b, DD3/2025b, DD3/2023b) next to this script, the
run-directory helper lhcd_module_run_setup.sh and the source archive
<work>/sources/l/LHCD-MODULE/lhcd-module-<VERSION>.tar.gz (git archive of COMMIT from the local
lhcd-module clone, prefix lhcd-module/).

LHCD_METIS is a pure Python code: no compilation. The actor package lhcd_metis is made by the
repository's ./generate_actor (iWrap Python actor envelope from lhcd_metis.yaml / lhcd_metis_dd3.yaml,
then lhcd_metis_template/actor.py and the model files copied into it), as ci-sdcc/st02-build-actor.sh.

Dependencies = the `modules` list of the matching combination of deps.yaml at the pinned commit, in the
same order; IMAS_VERSION = its imas_version (no IMAS-Fortran module). On intel-2023b, IMAS-Python
2.3.0-intel-2023b brings IMAS-Core 5.5.2. Rerun this script after editing the helper template (its
checksum is written into the easyconfigs).
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, '..', '_lib'))
import hcd_ec as hcd  # noqa: E402

# Version label = build date of the module; built from COMMIT (origin/feature/DD3_and_DD4,
# git describe DESCRIBE).
VERSION = hcd.version_of('LHCD-MODULE')
COMMIT = '55a445eae49036c7f0eaeac5cbc0b1926df6fe9a'
DESCRIBE = 'v2_dd3&4_al5_JINTRACv36-3-g55a445e'
REPO = hcd.repo('lhcd-module', 'LHCD-MODULE')
HELPER = 'lhcd_module_run_setup.sh'


def deps(tc, dd):
    return [hcd.d_imaspy(), hcd.d_iwrap(), hcd.d_muscle3(tc)]


TEMPLATE = '''# LHCD-MODULE (LHCD_METIS lower-hybrid current drive, pure Python) as iWrap Python actor and MUSCLE3
# actor: DD @DD@, toolchain intel/@TC@, combination @COMBO@ of deps.yaml.
# Generated by gen_easyconfigs.py; edit the generator, not this file.
easyblock = 'Binary'

name = 'LHCD-MODULE'
version = '@VERSION@'
local_dd = '@DD@'
versionsuffix = '-DD-%s' % local_dd

# Version @VERSION@ (date label) = commit @COMMIT@ of origin/feature/DD3_and_DD4,
# git@gitlab.eufus.psnc.pl:g2tfong/lhcd-module.git (git describe @DESCRIBE@); source archive
# lhcd-module-@VERSION@.tar.gz = git archive --prefix=lhcd-module/ of that commit.
local_commit = '@COMMIT@'
local_combo = '@COMBO@'

homepage = 'https://gitlab.eufus.psnc.pl/g2tfong/lhcd-module'
description = """LHCD_METIS: lower-hybrid current-drive model (pure Python, IMAS-Python).
Version @VERSION@ is a date label: built from commit %s (git describe @DESCRIBE@) of
origin/feature/DD3_and_DD4, for DD %s: iWrap Python actor package lhcd_metis (on PYTHONPATH; generated by
./generate_actor, with the MUSCLE3 actor lhcd_metis/lhcd_metis_m3.py), and the run kit run_kit
(run_lhcd.py, run_muscle, coupling.ymmsl, lhcd_metis_m3.py, input, ci-sdcc with the WEST 57757 CI entry);
lhcd_module_run_setup <dir> makes a writable run directory from it.""" % (local_commit, local_dd)

toolchain = {'name': 'intel', 'version': '@TC@'}

sources = [
    {
        'git_config': {
            'url': 'git@gitlab.eufus.psnc.pl:g2tfong',
            'repo_name': 'lhcd-module',
            'commit': local_commit,
        },
        'filename': '%(namelower)s-%(version)s.tar.gz',
    },
    {
        'filename': '@HELPER@',
        'extract_cmd': 'cp %s .',
    },
]
checksums = [
    None,
    '@HELPER_SHA@',
]
extract_sources = True

# combination @COMBO@ of deps.yaml (same order)
dependencies = [
@DEPS@
]

# Environment of ci-sdcc/st00-header.sh for this code: COMBO and IMAS_VERSION of the combination
# (imas_version of deps.yaml), no compiler
local_env = ' && '.join([
    '@UNSET@',
    'export COMBO=%s IMAS_VERSION=%s' % (local_combo, local_dd),
])
# ACTORS_COPY_DIR=none: ci-sdcc/copy_actors.sh of the build scripts copies no actor into ~/public/PYTHON_ACTORS
local_env += ' && export ACTORS_COPY_DIR=none'
local_src = '%(builddir)s/lhcd-module'
local_kit = '%(installdir)s/run_kit'

install_cmds = [
    # st02-build-actor.sh: ./generate_actor -o $ACTOR_FOLDER (yaml from IMAS_VERSION; writes the build
    # stamp lhcd_metis/.build_combo)
    local_env + ' && cd ' + local_src + ' && ./generate_actor -o %(installdir)s',
    # run kit: run scripts, model files, inputs and the CI entry of the repository; ./lhcd_metis is a link
    # to the actor package of the module (build-stamp check of run_lhcd.py / run_muscle without ACTOR_FOLDER)
    'mkdir -p ' + local_kit + ' && cd ' + local_src +
    ' && cp -p __init__.py run_lhcd.py dd_compat.py module_lhhcd.py lhcd_metis_m3.py generate_actor'
    ' lhcd_metis.yaml lhcd_metis_dd3.yaml coupling.ymmsl run_muscle ' + local_kit + '/'
    ' && cp -rp lhcd_metis_template input ci-sdcc ' + local_kit + '/',
    'cd ' + local_kit + ' && chmod a+x run_lhcd.py run_muscle generate_actor'
    ' && ln -sfn %(installdir)s/lhcd_metis lhcd_metis',
    'mkdir -p %(installdir)s/bin && install -m 0755 %(builddir)s/@HELPER@ %(installdir)s/bin/lhcd_module_run_setup',
    'find %(installdir)s -name __pycache__ -type d -prune -exec rm -rf {} +',
]
prepend_to_path = ['bin']

modextrapaths = {'PYTHONPATH': ''}
modextravars = {
    'IMAS_VERSION': local_dd,
    'COMBO': local_combo,
    'IMAS_AL_DISABLE_OBSOLESCENT_WARNING': '1',
    'LHCD_MODULE_RUN_KIT': local_kit,
}

sanity_check_paths = {
    'files': ['bin/lhcd_module_run_setup', 'lhcd_metis/actor.py', 'lhcd_metis/module_lhhcd.py',
              'lhcd_metis/dd_compat.py', 'lhcd_metis/lhcd_metis_m3.py', 'lhcd_metis/.build_combo',
              'run_kit/run_lhcd.py', 'run_kit/run_muscle', 'run_kit/coupling.ymmsl', 'run_kit/lhcd_metis_m3.py',
              'run_kit/ci-sdcc/st03-run-actor.sh', 'run_kit/ci-sdcc/st03-imasdb/WEST/3/57757/1/master.h5'],
    'dirs': ['lhcd_metis/common', 'run_kit/input'],
}

sanity_check_commands = [
    "python -c 'from lhcd_metis.actor import lhcd_metis'",
    "python -c 'import ymmsl, libmuscle'",
    "grep -q \\"data_dictionary_compliant.*%s\\" %%(installdir)s/lhcd_metis/common/actor_info.py" % (
        '4.0.0' if local_dd.startswith('4') else '3.42.0'),
    'bash %(installdir)s/run_kit/ci-sdcc/build_stamp.sh check %(installdir)s/lhcd_metis lhcd-module',
    'lhcd_module_run_setup --help',
]

moduleclass = 'phys'
'''


def main():
    hcd.make_archive('LHCD-MODULE', REPO, COMMIT, 'lhcd-module')
    sha = hcd.write_helper(
        os.path.join(HERE, HELPER), 'lhcd_module_run_setup', 'LHCD_METIS', 'LHCD-MODULE', 'EBROOTLHCDMINMODULE',
        'lhcd_metis/ actor package with its build stamp', '<run_dir>', '',
        ['python run_lhcd.py -s <scenario.yaml> -c input/params.xml   # iWrap actor',
         './run_muscle -s <scenario.yaml>                               # MUSCLE3 actor'])
    flavours = {k: {'deps': deps(tc, dd)} for k, (tc, dd, fc) in hcd.TC_DD_FC.items()}
    hcd.write_template(HERE, 'LHCD-MODULE', VERSION, TEMPLATE, flavours, {
        'COMMIT': COMMIT, 'DESCRIBE': DESCRIBE, 'HELPER': HELPER, 'HELPER_SHA': sha,
        'UNSET': hcd.UNSET_TOOLCHAIN_ENV})


if __name__ == '__main__':
    main()
