#!/usr/bin/env python3
"""Writes the three HCD_MERGERS easyconfigs (DD4/2025b, DD3/2025b, DD3/2023b) next to this script,
the run-directory helper hcd_mergers_run_setup.sh and the source archive
<work>/sources/h/HCD_MERGERS/hcd_mergers-<VERSION>.tar.gz (git archive of COMMIT from the
local hcd-mergers clone, prefix hcd-mergers/).

Dependencies = the `modules` list of the matching combination of deps.yaml at the pinned commit,
in the same order (deps.yaml lists no components). Rerun this script after editing the helper
template (its checksum is written into the easyconfigs).
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, '..', '_lib'))
import hcd_ec as hcd  # noqa: E402

# Version label = build date of the module; built from COMMIT (origin/feature/DD3_and_DD4,
# git describe DESCRIBE).
VERSION = hcd.version_of('HCD_MERGERS')
COMMIT = '452f69340d5ed9ced424943510f1b28bc7ddbd01'
DESCRIBE = '1.0.0-5-g452f693'
REPO = hcd.repo('hcd-mergers', 'HCD_MERGERS')
HELPER = 'hcd_mergers_run_setup.sh'
ACTORS = ['merge_core_sources', 'merge_distribution_sources', 'merge_distributions', 'merge_waves']


def deps(tc, dd):
    return [hcd.d_iwrap(), hcd.d_imaspy(), hcd.d_imasf(dd), hcd.d_idstools(), hcd.d_muscle3(tc), hcd.d_xmllib(tc)]


TEMPLATE = '''# HCD_MERGERS (merge_core_sources, merge_distribution_sources, merge_distributions, merge_waves)
# as Fortran library, iWrap actors and MUSCLE3 actors: DD @DD@, toolchain intel/@TC@ (@FC@),
# combination @COMBO@ of deps.yaml.
# Generated by gen_easyconfigs.py; edit the generator, not this file.
easyblock = 'MakeCp'

name = 'HCD_MERGERS'
version = '@VERSION@'
local_dd = '@DD@'
versionsuffix = '-DD-%s' % local_dd

# Version @VERSION@ (date label) = commit @COMMIT@ of origin/feature/DD3_and_DD4,
# ssh://git@git.iter.org/heat/hcd-mergers.git (git describe @DESCRIBE@); source archive
# hcd_mergers-@VERSION@.tar.gz = git archive --prefix=hcd-mergers/ of that commit.
local_commit = '@COMMIT@'
local_combo = '@COMBO@'
local_fc = '@FC@'
local_actors = @ACTORS@

homepage = 'https://git.iter.org/projects/HEAT/repos/hcd-mergers'
description = """H&CD mergers: merge two waves, distributions, distribution_sources or core_sources IDSs.
Version @VERSION@ is a date label: built from commit %s (git describe @DESCRIBE@) of
origin/feature/DD3_and_DD4, for DD %s: Fortran library (lib, include/hcd_mergers), iWrap actor packages
merge_core_sources, merge_distribution_sources, merge_distributions, merge_waves (on PYTHONPATH), each with
its MUSCLE3 actor <actor>/<actor>_m3.exe (also in bin), and the run kit run_kit (run_mergers.py,
run_muscle, coupling.ymmsl); hcd_mergers_run_setup <dir> makes a writable run directory from it.""" % (
    local_commit, local_dd)

toolchain = {'name': 'intel', 'version': '@TC@'}

sources = [
    {
        'git_config': {
            'url': 'ssh://git@git.iter.org/heat',
            'repo_name': 'hcd-mergers',
            'commit': local_commit,
        },
        'filename': '%(namelower)s-%(version)s.tar.gz',
    },
    {
        'filename': '@HELPER@',
        'extract_cmd': 'cp %s .',
    },
]
checksums = [
    None,
    '@HELPER_SHA@',
]
start_dir = '%(builddir)s/hcd-mergers'

dependencies = [
@DEPS@
]

# Build environment of ci-sdcc/st00-header.sh: no toolchain compiler flags, FC of the toolchain,
# COMBO and IMAS_VERSION of the combination
local_env = ' && '.join([
    '@UNSET@',
    'export FC=%s COMBO=%s IMAS_VERSION=%s' % (local_fc, local_combo, local_dd),
])
# ACTORS_COPY_DIR=none: ci-sdcc/copy_actors.sh of the build scripts copies no actor into ~/public/PYTHON_ACTORS
local_env += ' && export ACTORS_COPY_DIR=none'

# st01-build-code.sh: make -C mergers/ clean library FC=$FC
prebuildopts = local_env + ' && '
buildopts = '-C mergers FC=%s' % local_fc
build_cmd_targets = 'clean library'
# the Makefile archives *.o: serial build
maxparallel = 1

files_to_copy = [
    (['mergers/libmergers.a'], 'lib'),
    (['mergers/*.mod'], 'include/hcd_mergers'),
]

local_kit = '%(installdir)s/run_kit'
postinstallcmds = [
    # st02-build-actor.sh: iWrap actors (yaml per FC and DD) and MUSCLE3 actors merge_*_m3.exe, both in
    # ACTOR_FOLDER=%(installdir)s (merge_*/merge_*_m3.exe, where coupling.ymmsl and HCD-WF expect them)
    local_env + ' && cd %(start_dir)s && make -C mergers/ iwrapactor FC=$FC ACTOR_FOLDER=%(installdir)s',
    local_env + ' && cd %(start_dir)s && make -C mergers/ m3 FC=$FC ACTOR_FOLDER=%(installdir)s',
    'mkdir -p %(installdir)s/bin && cd %(start_dir)s/mergers && cp -p merge_*_m3.exe %(installdir)s/bin/',
    # run kit: run scripts of the repository root; the actor folders are links to the module
    'mkdir -p ' + local_kit + ' && cd %(start_dir)s'
    ' && cp -p run_mergers.py run_muscle coupling.ymmsl build.sh ' + local_kit + '/'
    ' && cp -rp ci-sdcc ' + local_kit + '/',
    'cd ' + local_kit + ' && chmod a+x run_mergers.py run_muscle build.sh'
    ' && for a in %s; do ln -sfn %%(installdir)s/$a $a; done' % ' '.join(local_actors),
    # build stamp of the combination (read by run_muscle through ci-sdcc/build_stamp.sh)
    local_env + ' && cd ' + local_kit + ' && bash ci-sdcc/build_stamp.sh write .',
    'install -m 0755 %(builddir)s/@HELPER@ %(installdir)s/bin/hcd_mergers_run_setup',
    'find %(installdir)s -name __pycache__ -type d -prune -exec rm -rf {} +',
]

modextrapaths = {'PYTHONPATH': ''}
modextravars = {
    'IMAS_VERSION': local_dd,
    'COMBO': local_combo,
    'HCD_MERGERS_RUN_KIT': local_kit,
}
# stack limit of config_sdcc*.sh (Fortran automatic arrays)
modluafooter = 'execute{cmd="ulimit -Ss unlimited 2>/dev/null || true", modeA={"load"}}'

sanity_check_paths = {
    'files': ['lib/libmergers.a', 'bin/hcd_mergers_run_setup', 'run_kit/run_mergers.py', 'run_kit/run_muscle',
              'run_kit/coupling.ymmsl', 'run_kit/.build_combo', 'run_kit/ci-sdcc/build_stamp.sh'] +
             ['%s/actor.py' % a for a in local_actors] +
             ['%s/%s_m3.exe' % (a, a) for a in local_actors] +
             ['bin/%s_m3.exe' % a for a in local_actors],
    'dirs': ['include/hcd_mergers'],
}

sanity_check_commands = ["python -c 'from %s.actor import %s'" % (a, a) for a in local_actors] + [
    "python -c 'import ymmsl, libmuscle'",
] + ["! ldd %%(installdir)s/%s/%s_m3.exe | grep 'not found'" % (a, a) for a in local_actors] + [
    "ldd %%(installdir)s/bin/%s_m3.exe | grep -q libmuscle" % local_actors[0],
    'test "$IMAS_VERSION" = "$(pkg-config --modversion al-fortran | cut -d- -f1)"',
    'bash %(installdir)s/run_kit/ci-sdcc/build_stamp.sh check %(installdir)s/run_kit hcd-mergers',
    'hcd_mergers_run_setup --help',
]

moduleclass = 'phys'
'''


def main():
    hcd.make_archive('HCD_MERGERS', REPO, COMMIT, 'hcd-mergers')
    sha = hcd.write_helper(
        os.path.join(HERE, HELPER), 'hcd_mergers_run_setup', 'HCD_MERGERS', 'HCD_MERGERS', 'EBROOTHCD_MERGERS',
        'merge_*/ with the MUSCLE3 actors, build stamp .build_combo', '<run_dir>', '',
        ['python run_mergers.py    # iWrap actors (4 mergers on dummy IDSs)',
         './run_muscle             # MUSCLE3 actors (muscle_manager --start-all coupling.ymmsl)'])
    flavours = {k: {'deps': deps(tc, dd)} for k, (tc, dd, fc) in hcd.TC_DD_FC.items()}
    hcd.write_template(HERE, 'HCD_MERGERS', VERSION, TEMPLATE, flavours, {
        'COMMIT': COMMIT, 'DESCRIBE': DESCRIBE, 'HELPER': HELPER, 'HELPER_SHA': sha,
        'ACTORS': repr(ACTORS), 'UNSET': hcd.UNSET_TOOLCHAIN_ENV})


if __name__ == '__main__':
    main()
